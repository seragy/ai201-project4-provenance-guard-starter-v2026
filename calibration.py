def main():
    import detector

    model_only = "--model" in sys.argv
    if model_only:
        print(f"{'input':<18}{'expect':<8}{'model':>7}")
        for name, expect, text in CALIBRATION:
            print(f"{name:<18}{expect:<8}{detector.model_signal(text):>7.3f}")
        return

    import scoring
    import stylometry

    head = (f"{'input':<18}{'expect':<7}{'model':>7}{'style':>7}{'combined':>9}"
            f"  {'guess':<7}{'spread':>7}{'ttr':>6}{'punct':>6}")
    print(head)
    print("-" * len(head))
    for name, expect, text in CALIBRATION:
        m = detector.model_signal(text)
        s = stylometry.style_signal(text)
        c = scoring.combine_signals(m, s)
        guess, _ = scoring.score_to_label(c)
        print(f"{name:<18}{expect:<7}{m:>7.3f}{s:>7.3f}{c:>9.3f}  {guess:<7}"
              f"{stylometry.sentence_length_spread(text):>7.2f}"
              f"{stylometry.type_token_ratio(text):>6.2f}"
              f"{stylometry.punctuation_density(text):>6.2f}")


if __name__ == "__main__":
    main()
